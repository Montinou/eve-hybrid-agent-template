// Regenerates agent/lib/instructions-hash.ts from agent/instructions.md.
//
// Why a generated module instead of reading the file at runtime: the deployed
// runtime has no repo filesystem (agent/instructions.md does not exist in the
// build output — eve inlines its content only into its own internal
// instructions manifest, not for authored modules that try to read it via
// fs). Any capability that wants to log which prompt version produced a
// result (e.g. tagging telemetry rows with a `system_prompt_hash`) needs the
// hash precompiled into the bundle like any other TS module.
//
// Modes:
//   node scripts/hash-instructions.mjs           # write/refresh the module
//   node scripts/hash-instructions.mjs --check   # CI gate: exit 1 on drift
//
// CI runs --check so an instructions.md edit that forgets to regenerate the
// hash module fails the build instead of silently logging a stale hash.
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const src = resolve(process.cwd(), "agent/instructions.md");
const out = resolve(process.cwd(), "agent/lib/instructions-hash.ts");

const markdown = await readFile(src, "utf8");
const hash = createHash("sha256").update(markdown, "utf8").digest("hex");
const contents =
  "// Generated by scripts/hash-instructions.mjs from ../instructions.md — do not edit by hand.\n" +
  `export default ${JSON.stringify(hash)};\n`;

if (process.argv.includes("--check")) {
  let existing = null;
  try {
    existing = await readFile(out, "utf8");
  } catch {
    // Missing file counts as drift; reported below.
  }
  if (existing !== contents) {
    console.error(
      `[hash-instructions] ${out} is out of sync with ${src}.\n` +
        "Run `node scripts/hash-instructions.mjs` and commit the result.",
    );
    process.exit(1);
  }
  console.log(`[hash-instructions] in sync (sha256 ${hash})`);
} else {
  await writeFile(out, contents);
  console.log(`[hash-instructions] instructions-hash.ts synced from ${src} (sha256 ${hash})`);
}
